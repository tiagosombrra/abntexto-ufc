const REQUIRED_KEYS = Object.freeze([
  "pageTitle", "description", "privacyTitle", "privacyText", "filterAria",
  "rulesStats", "showing", "selectFile", "validating", "validationFailed",
  ...Object.keys(STATIC_TARGETS),
  ...Object.values(OPTION_TARGETS).flat(),
  ...CANONICAL_STATUS.map(s => "status" + s),
  ...CANONICAL_VERDICT.map(v => "verdict" + v)
]);

export function uiText(key, ...values) {
  const copy = COPIES[activeLocale];
  if (!Object.hasOwn(copy, key) || typeof copy[key] !== "string" || !copy[key].trim()) {
    throw new Error("Missing Web/Lite UI translation: " + activeLocale + "/" + key);
  }
  return copy[key].replace(/\{(\d+)\}/g, (_, n) => {
    const i = Number(n);
    if (i >= values.length) throw new Error("Missing interpolation argument: " + key);
    return String(values[i]);
  });
}
export function getLocale() { return activeLocale; }
export function assertLocaleCoverage() {
  for (const locale of SUPPORTED_LOCALES) {
    if (!COPIES[locale] || Object.keys(COPIES[locale]).length !== Object.keys(COPIES["pt-BR"]).length) {
      throw new Error("Incomplete Web/Lite locale dictionary: " + locale);
    }
    for (const key of REQUIRED_KEYS) {
      if (!Object.hasOwn(COPIES[locale], key) || !String(COPIES[locale][key]).trim()) {
        throw new Error("Incomplete Web/Lite locale: " + locale + "/" + key);
      }
    }
  }
  return true;
}
export function setLocale(locale) {
  if (!SUPPORTED_LOCALES.includes(locale)) throw new RangeError("Unsupported Web/Lite interface locale: " + locale);
  assertLocaleCoverage();
  // Check the full controlled DOM contract before changing any user-facing text.
  for (const selector of Object.values(STATIC_TARGETS)) {
    if (!document.querySelector(selector)) throw new Error("Missing Web/Lite locale target: " + selector);
  }
  for (const [selector, keys] of Object.entries(OPTION_TARGETS)) {
    const element = document.querySelector(selector);
    if (!element || element.options.length !== keys.length
      || keys.some((key, i) => element.options[i].value !== key)) {
      throw new Error("Web/Lite canonical option mismatch: " + selector);
    }
  }
  const privacy = document.querySelector("section.controls > p.note");
  if (!privacy || !privacy.firstElementChild || !privacy.lastChild) {
    throw new Error("Missing Web/Lite privacy disclosure");
  }
  activeLocale = locale;
  document.documentElement.lang = locale;
  document.title = uiText("pageTitle");
  const meta = document.querySelector('meta[name="description"]');
  if (!meta) throw new Error("Missing Web/Lite page description");
  meta.content = uiText("description");
  for (const [key, selector] of Object.entries(STATIC_TARGETS)) {
    document.querySelector(selector).textContent = uiText(key);
  }
  privacy.firstElementChild.textContent = uiText("privacyTitle");
  privacy.lastChild.textContent = uiText("privacyText");
  document.querySelector("#report-section .actions[role=group]").setAttribute("aria-label", uiText("filterAria"));
  for (const [selector, keys] of Object.entries(OPTION_TARGETS)) {
    const options = document.querySelector(selector).options;
    keys.forEach((key, i) => { options[i].textContent = uiText(key); });
  }
  return locale;
}
